object AndroidL10n {
    fun t(key: String, lang: String): String {
        val language = normalizedLanguageCode(lang)
        return localizedOverrides[language]?.get(key)
            ?: strings[language]?.get(key)
            ?: strings["en"]?.get(key)
            ?: strings["ru"]?.get(key)
            ?: key
    }

    private fun normalizedLanguageCode(raw: String): String {
        val lower = raw.lowercase()
        return when {
            lower.startsWith("fr") -> "fr"
            lower.startsWith("it") -> "it"
            lower.startsWith("es") -> "es"
            lower.startsWith("en") -> "en"
            else -> "ru"
        }
    }

